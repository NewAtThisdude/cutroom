"""Cutroom lip sync, run on the RTX 4090 PC: LatentSync 1.6 (ByteDance; code Apache-2.0, weights CreativeML OpenRAIL++-M)
re-syncs the mouth in REAL footage to new speech. Each frame's face is cropped (InsightFace landmarks), its lower half is
regenerated by the model for the speech around that frame, and the crop is warped back with LatentSync's soft mask: every
pixel outside the face is the input frame's own, and the motion is the footage's own.

  python lipsync_gpu.py <job.json>     (from the LatentSync checkout: its configs/ and checkpoints/ are relative paths)
  job = {"pieces": [{"video": in.mp4, "audio": in.wav, "out": out.mp4}], "w": 1280, "h": 720, "fps": "30000/1001", "steps": 20, "guidance": 1.5, "seed": 1247}

Changes to stock LatentSync, all here (its files stay as pinned): frames are read at the clip's own rate (stock resamples
to 25 fps, so the frames would not be the clip's), the speech features are cut at that rate; a frame without a face
is passed through unchanged (stock stops: "Face not detected"); the output keeps exactly the input's frames (stock
loops the video to the audio's length) and is written at near-lossless quality without sound.
Prints "piece <i> <frames> <frames with a face>" per piece, then "done"; one model load for all pieces.
"""
import json
import os
import subprocess
import sys
import types
from fractions import Fraction

sys.path.insert(0, os.getcwd())  # run from the LatentSync checkout; this file comes with each job
os.environ['PATH'] = os.path.dirname(sys.executable) + os.pathsep + os.environ.get('PATH', '')  # its ffmpeg.exe (gpu_setup.ps1: imageio-ffmpeg's)

import imageio_ffmpeg
import numpy as np
import torch
from omegaconf import OmegaConf
from diffusers import AutoencoderKL, DDIMScheduler
from DeepCache import DeepCacheSDHelper
from accelerate.utils import set_seed
from latentsync.models.unet import UNet3DConditionModel
from latentsync.pipelines import lipsync_pipeline as lp
from latentsync.whisper.audio2feature import Audio2Feature

FFMPEG = imageio_ffmpeg.get_ffmpeg_exe()
SWS = ['-sws_flags', 'accurate_rnd+full_chroma_int+bicubic']
OUT, SIZE = [], {}  # SIZE: video path -> (w, h), from the job


def read(path):  # the clip's own frames (stock resamples to 25 fps), BT.709 both ways (OpenCV's decoder would use BT.601)
    w, h = SIZE[path]
    raw = subprocess.run([FFMPEG, '-v', 'error', '-i', path, *SWS, '-vf', 'scale=in_color_matrix=bt709:in_range=tv', '-f', 'rawvideo', '-pix_fmt', 'rgb24', '-'],
                         capture_output=True, check=True).stdout
    return np.frombuffer(raw, np.uint8).reshape(-1, h, w, 3).copy()


lp.read_video = lambda path, use_decord=False: read(path)
lp.write_video = lambda path, frames, fps: OUT.append(frames)  # kept in memory, written below
lp.subprocess = types.SimpleNamespace(run=lambda *a, **k: None)  # stock muxes a crf-18 copy with sound: not needed


class NoFace(Exception):
    pass


class Pipe(lp.LipsyncPipeline):
    def affine_transform_video(self, frames):
        got = []
        for fr in frames:
            try:
                got.append(self.image_processor.affine_transform(fr))
            except RuntimeError:  # "Face not detected": this frame is passed through
                got.append(None)
        self.found = [g is not None for g in got]
        if not any(self.found):
            raise NoFace()
        fill = next(g for g in got if g)  # a stand-in crop for faceless frames (their result is thrown away)
        for i, g in enumerate(got):
            fill = g or fill
            got[i] = fill
        return torch.stack([g[0] for g in got]), [g[1] for g in got], [g[2] for g in got]

    def loop_video(self, chunks, frames):
        # the speech can be a few chunks longer than the frames: the last frame repeats for them (stock plays the video
        # backwards); those extra frames are dropped again after
        frames = frames[:len(chunks)]
        faces, boxes, mats = self.affine_transform_video(frames)
        k = len(chunks) - len(frames)
        if k > 0:
            frames = np.concatenate([frames, np.repeat(frames[-1:], k, axis=0)])
            faces = torch.cat([faces, faces[-1:].repeat(k, 1, 1, 1)])
            boxes, mats, self.found = boxes + boxes[-1:] * k, mats + mats[-1:] * k, self.found + self.found[-1:] * k
        return frames, faces, boxes, mats

    def restore_video(self, faces, frames, boxes, mats):
        out = super().restore_video(faces, frames, boxes, mats)
        for i, ok in enumerate(self.found[:len(out)]):
            if not ok:
                out[i] = frames[i]
        return out


def main(job):
    if torch.cuda.mem_get_info()[0] < 17 << 30:
        raise SystemExit(f'the GPU has {torch.cuda.mem_get_info()[0] / 2**30:.1f} GB free; lip sync needs about 18 GB (something else is using it)')
    config = OmegaConf.load('configs/unet/stage2_512.yaml')
    fps = Fraction(str(job['fps']))
    audio = Audio2Feature(model_path='checkpoints/whisper/tiny.pt', device='cuda', num_frames=config.data.num_frames,
                          audio_feat_length=config.data.audio_feat_length)
    vae = AutoencoderKL.from_pretrained('checkpoints/sd-vae-ft-mse', torch_dtype=torch.float16)
    vae.config.scaling_factor, vae.config.shift_factor = 0.18215, 0
    unet, _ = UNet3DConditionModel.from_pretrained(OmegaConf.to_container(config.model), 'checkpoints/latentsync_unet.pt', device='cpu')
    pipe = Pipe(vae=vae, audio_encoder=audio, unet=unet.to(dtype=torch.float16), scheduler=DDIMScheduler.from_pretrained('configs')).to('cuda')
    helper = DeepCacheSDHelper(pipe=pipe)
    helper.set_params(cache_interval=3, cache_branch_id=0)
    helper.enable()
    for i, pc in enumerate(job['pieces']):
        SIZE[pc['video']] = (int(job['w']), int(job['h']))
        set_seed(int(job.get('seed', 1247)))
        n = len(read(pc['video']))
        OUT.clear()
        try:
            pipe(video_path=pc['video'], audio_path=pc['audio'], video_out_path=pc['out'] + '.unused.mp4', num_frames=config.data.num_frames,
                 video_fps=float(fps), num_inference_steps=int(job.get('steps', 20)), guidance_scale=float(job.get('guidance', 1.5)),
                 weight_dtype=torch.float16, width=config.data.resolution, height=config.data.resolution,
                 mask_image_path=config.data.mask_image_path, temp_dir=pc['out'] + '.tmp')
            frames, faces = OUT[0][:n], sum(pipe.found[:n])
        except NoFace:
            frames, faces = read(pc['video']), 0  # no face anywhere: the piece as it was
        enc = subprocess.run([FFMPEG, '-v', 'error', '-y', '-f', 'rawvideo', '-pix_fmt', 'rgb24', '-s', f"{job['w']}x{job['h']}", '-r', str(fps), '-i', '-',
                              *SWS, '-vf', 'scale=out_color_matrix=bt709:out_range=tv', '-c:v', 'libx264', '-crf', '8', '-preset', 'fast', '-pix_fmt', 'yuv420p',
                              '-colorspace', 'bt709', '-color_primaries', 'bt709', '-color_trc', 'bt709', pc['out']], input=np.ascontiguousarray(frames).tobytes())
        if enc.returncode:
            raise SystemExit('could not write ' + pc['out'])
        print(f'piece {i} {n} {faces}', flush=True)
    print('done', flush=True)


if __name__ == '__main__':
    main(json.load(open(sys.argv[1])))
